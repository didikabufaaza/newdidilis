const groupLabels: Record<string, string> = {
  utama: "",
  pemeriksaan: "PEMERIKSAAN",
  master: "MASTER DATA",
  pengaturan: "PENGATURAN",
  laporan: "LAPORAN",
  ai: "ANALISA",
  admin: "ADMINISTRASI",
};

export default function Sidebar({ user }: SidebarProps) {
  const pathname = usePathname();
  const [collapsed, setCollapsed] = useState(false);
  const [mobileOpen, setMobileOpen] = useState(false);

  // Read view-as role from localStorage to filter menus
  const [viewAsRole, setViewAsRole] = useState<string | null>(null);
  const [canAnalyze, setCanAnalyze] = useState(false);
  useEffect(() => {
    const role = localStorage.getItem("viewAsUserRole");
    if (role) setViewAsRole(role);
    setCanAnalyze(localStorage.getItem("canAnalyze") === "true");
  }, []);

  const effectiveRole = viewAsRole || user.role;

  const handleLogout = async () => {
    await fetch("/api/auth/logout", { method: "POST" });
    localStorage.removeItem("lis_token");
    localStorage.removeItem("viewAsUserId");
    localStorage.removeItem("viewAsUserRole");
    window.location.href = "/login";
  };

  const isActive = (href: string) => {
    if (href === "/dashboard") return pathname === "/dashboard";
    return pathname.startsWith(href);
  };

  const filteredItems = navItems.filter(
    (item) =>
      (!item.role || item.role === effectiveRole) &&
      (!item.aiOnly || canAnalyze)
  );

  const groupedItems: { group: string; label: string; items: NavItem[] }[] = [];
  let lastGroup = "";
  for (const item of filteredItems) {
    const g = item.group || "other";
    if (g !== lastGroup) {
      groupedItems.push({ group: g, label: groupLabels[g] || g, items: [] });
      lastGroup = g;
    }
    groupedItems[groupedItems.length - 1].items.push(item);
  }

  const NavContent = () => (
    <div className="flex flex-col h-full">
      {/* Logo */}
      <div className="flex items-center gap-3 px-4 py-4 border-b border-blue-700/50">
        <div className="bg-white rounded-lg p-1 shadow-md flex-shrink-0">
          <img
            src="/didilis.png"
            alt="di-diLIS — didik-digital Laboratory Information System"
            className="h-9 w-[90px] object-contain"
          />
        </div>
        {!collapsed && (
          <div className="min-w-0">
            <p className="text-white font-extrabold text-[15px] leading-tight tracking-tight">
              di-diLIS
            </p>
            <p className="text-[8.5px] text-blue-200/90 leading-tight">
              didik-digital Laboratory
              <br />
              Information System
            </p>
          </div>
        )}
      </div>

      {/* Navigation */}
      <nav className="flex-1 py-4 px-3 space-y-0 overflow-y-auto">
        {groupedItems.map((group, gi) => (
          <div key={group.group}>
            {group.label && !collapsed && (
              <p className="text-[10px] font-bold text-blue-300/60 uppercase tracking-widest px-3 pt-4 pb-1.5">
                {group.label}
              </p>
            )}
            {gi > 0 && <div className="border-t border-blue-600/30 mx-3 my-2" />}
            {group.items.map((item) => {
              const active = isActive(item.href);
              return (
                <Link
                  key={item.href}
                  href={item.href}
                  onClick={() => setMobileOpen(false)}
                  className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-all ${
                    active
                      ? "bg-white/20 text-white shadow-sm"
                      : "text-blue-100 hover:bg-white/10 hover:text-white"
                  }`}
                >
                  <span className="flex-shrink-0">{item.icon}</span>
                  {!collapsed && <span className="truncate">{item.label}</span>}
                </Link>
              );
            })}
          </div>
        ))}
      </nav>

      {/* User */}
      <div className="border-t border-blue-700/50 p-4">
        {!collapsed && (
          <div className="mb-3 flex items-center gap-3">
            <div className="w-9 h-9 rounded-full bg-white/20 flex items-center justify-center text-white font-bold text-sm flex-shrink-0">
              {user.name.charAt(0)}
            </div>
            <div className="min-w-0">
              <p className="text-sm font-medium text-white truncate">{user.name}</p>
              <p className="text-xs text-blue-200 truncate">{roleLabels[user.role] || user.role}</p>
            </div>
          </div>
        )}
        <button
          onClick={handleLogout}
          className="flex items-center gap-3 w-full px-3 py-2 rounded-lg text-sm text-blue-100 hover:bg-white/10 hover:text-white transition-all"
        >
          <svg className="w-5 h-5 flex-shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={1.5}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0 0 13.5 3h-6a2.25 2.25 0 0 0-2.25 2.25v13.5A2.25 2.25 0 0 0 7.5 21h6a2.25 2.25 0 0 0 2.25-2.25V15m3 0 3-3m0 0-3-3m3 3H9" />
          </svg>
          {!collapsed && <span>Keluar</span>}
        </button>
      </div>
    </div>
  );

  return (
    <>
      {/* Mobile toggle button */}
      <button
        onClick={() => setMobileOpen(true)}
        className="lg:hidden fixed top-4 left-4 z-40 bg-blue-600 text-white p-2.5 rounded-lg shadow-lg"
        aria-label="Menu"
      >
        <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={2}>
          <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
        </svg>
      </button>

      {/* Mobile overlay */}
      {mobileOpen && (
        <div
          className="lg:hidden fixed inset-0 bg-black/50 z-40"
          onClick={() => setMobileOpen(false)}
        />
      )}

      {/* Mobile sidebar */}
      <aside
        className={`lg:hidden fixed inset-y-0 left-0 z-50 w-64 bg-gradient-to-b from-blue-800 to-blue-900 transform transition-transform duration-300 ${
          mobileOpen ? "translate-x-0" : "-translate-x-full"
        }`}
      >
        <button
          onClick={() => setMobileOpen(false)}
          className="absolute top-4 right-4 text-white/60 hover:text-white"
          aria-label="Close"
        >
          <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={2}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M6 18 18 6M6 6l12 12" />
          </svg>
        </button>
        <NavContent />
      </aside>

      {/* Desktop sidebar */}
      <aside
        className={`hidden lg:flex flex-col bg-gradient-to-b from-blue-800 to-blue-900 transition-all duration-300 relative ${
          collapsed ? "w-[72px]" : "w-64"
        }`}
      >
        <button
          onClick={() => setCollapsed(!collapsed)}
          className="absolute -right-3 top-8 bg-white shadow-md rounded-full p-1 z-10 text-gray-500 hover:text-gray-700"
          aria-label="Collapse"
        >
          <svg
            className={`w-4 h-4 transition-transform ${collapsed ? "rotate-180" : ""}`}
            fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={2}
          >
            <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 19.5 8.25 12l7.5-7.5" />
          </svg>
        </button>
        <NavContent />
      </aside>
    </>
  );
}
